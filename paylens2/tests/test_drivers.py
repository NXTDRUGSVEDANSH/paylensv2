"""
Mix-vs-rate decomposition.

The analysis the brief is built around: an aggregate can fall while every
segment holds steady, because traffic moved toward a segment that was always
weaker. Reporting "X is failing" when X merely got more traffic is the error
this exists to prevent, and the two effects have different owners.
"""
from __future__ import annotations

import pytest

from paylens2.core import drivers as d
from paylens2.core.author import _coerce, validate


def seg(key, value, den):
    return d.Segment(key=key, value=value, denominator=den)


# ── the identity ────────────────────────────────────────────────────────────
def test_pure_mix_when_only_the_weights_move():
    # Two rails, neither changes its own rate, traffic moves to the weaker one.
    base = [seg("fast", 0.90, 900), seg("slow", 0.70, 100)]
    targ = [seg("fast", 0.90, 500), seg("slow", 0.70, 500)]
    r = d.decompose("rail", base, targ)
    assert r.delta_pp < 0
    assert r.rate_pp == pytest.approx(0.0, abs=1e-9), "no segment changed its rate"
    assert r.mix_pp == pytest.approx(r.delta_pp, abs=1e-9)
    assert r.dominant == "mix"


def test_pure_rate_when_only_the_segments_move():
    base = [seg("fast", 0.90, 500), seg("slow", 0.70, 500)]
    targ = [seg("fast", 0.80, 500), seg("slow", 0.60, 500)]
    r = d.decompose("rail", base, targ)
    assert r.mix_pp == pytest.approx(0.0, abs=1e-9), "no traffic moved"
    assert r.dominant == "rate"


def test_the_identity_holds_exactly():
    # delta = mix + rate, or the weights do not sum to one and the split is
    # meaningless. This residual is the correctness test, not a nicety.
    base = [seg("a", 0.91, 700), seg("b", 0.62, 200), seg("c", 0.80, 100)]
    targ = [seg("a", 0.88, 400), seg("b", 0.66, 500), seg("d", 0.50, 100)]
    r = d.decompose("rail", base, targ)
    assert abs(r.residual_pp) < 1e-9
    assert r.mix_pp + r.rate_pp == pytest.approx(r.delta_pp, abs=1e-9)


def test_a_segment_in_only_one_period_is_pure_mix():
    # A rail that did not exist last week cannot have "got worse".
    base = [seg("old", 0.90, 1000)]
    targ = [seg("old", 0.90, 900), seg("new", 0.50, 100)]
    r = d.decompose("rail", base, targ)
    new = next(s for s in r.segments if s.key == "new")
    assert new.rate_pp == pytest.approx(0.0, abs=1e-9)
    assert new.mix_pp != 0.0


def test_weights_come_from_volume_not_from_a_total_row():
    base = [seg("a", 0.9, 300), seg("b", 0.5, 100)]
    r = d.decompose("x", base, base)
    w = {s.key: s.weight_base for s in r.segments}
    assert w["a"] == pytest.approx(0.75) and w["b"] == pytest.approx(0.25)


def test_segments_are_ordered_by_how_much_they_moved():
    base = [seg("big", 0.9, 500), seg("small", 0.9, 500)]
    targ = [seg("big", 0.5, 500), seg("small", 0.89, 500)]
    r = d.decompose("x", base, targ)
    assert r.segments[0].key == "big"


def test_dimensions_are_ranked_by_concentration_not_by_delta():
    # Every dimension reports the SAME overall delta, so ranking by it is
    # useless. A dimension where two segments explain nearly everything points
    # somewhere specific; one that is smeared evenly does not.
    focused = d.decompose("focused", [seg("a", .9, 500), seg("b", .9, 500)],
                          [seg("a", .5, 500), seg("b", .9, 500)])
    smeared = d.decompose("smeared",
                          [seg(c, .9, 250) for c in "abcd"],
                          [seg(c, .8, 250) for c in "abcd"])
    assert d.rank_dimensions([smeared, focused])[0].dimension == "focused"


# ── the generated query ─────────────────────────────────────────────────────
def test_the_query_is_built_from_the_semantic_model():
    sql = d.decompose_sql("success_rate", "payment_method",
                          ("2026-11-02", "2026-11-09"), ("2026-11-09", "2026-11-16"))
    assert "is_success" in sql and "is_resolved" in sql, "not the model's formula"
    assert "'baseline'" in sql and "'target'" in sql
    assert "_num" in sql and "_den" in sql
    assert "v_attempts" in sql and "fact_" not in sql


def test_the_generated_query_passes_every_check():
    from backend.core import rbac
    from backend.core.guard import guard
    from paylens2.core import checks
    from paylens2.core.model import get_model
    m = get_model()
    sql = d.decompose_sql("success_rate", "payment_method",
                          ("2026-11-02", "2026-11-09"), ("2026-11-09", "2026-11-16"))
    # Generated by us is not a reason to trust it more than anything else.
    assert checks.check_v2(sql)
    assert guard(sql, rbac.principal_for("cxo", {}), m).checks_passed


def test_the_ratio_is_not_aliased_as_a_metric():
    # Only numerator and denominator are selected; Python divides them. Keeps
    # every figure computed where it can be shown, and leaves check 10d with
    # no column claiming to be a metric.
    sql = d.decompose_sql("success_rate", "payment_method",
                          ("2026-11-02", "2026-11-09"), ("2026-11-09", "2026-11-16"))
    assert " AS success_rate" not in sql


# ── against the real data ───────────────────────────────────────────────────
def test_it_reproduces_the_planted_mix_shift():
    from backend.core import rbac
    from backend.core.executor import execute
    from backend.core.guard import guard
    from paylens2.core.model import get_model
    sql = d.decompose_sql("success_rate", "payment_method",
                          ("2026-11-02", "2026-11-09"), ("2026-11-09", "2026-11-16"))
    rows = execute(guard(sql, rbac.principal_for("cxo", {}), get_model()).sql).rows
    r = d.decompose("payment_method", d.segments_from_rows(rows, "baseline"),
                    d.segments_from_rows(rows, "target"))
    # The generator plants a netbanking mix shift; these are the figures the
    # product has always quoted for it.
    assert r.delta_pp == pytest.approx(-1.33, abs=0.05)
    assert r.mix_pp == pytest.approx(-1.23, abs=0.05)
    assert abs(r.mix_share_pct) == pytest.approx(92.9, abs=1.0)
    assert r.dominant == "mix"
    assert abs(r.residual_pp) < 1e-9
    keys = [s.key for s in r.segments[:2]]
    assert "UPI" in keys and "NETBANKING" in keys


# ── the action ──────────────────────────────────────────────────────────────
@pytest.mark.parametrize("raw,expected", [
    ({"action": "decompose", "metric": "success_rate",
      "dimension": "payment_method", "window": "last week",
      "baseline": "the week before last"}, "decompose"),
    # inferred when the model omits `action`
    ({"metric": "success_rate", "dimension": "payment_method",
      "window": "a", "baseline": "b"}, "decompose"),
    # a count has no mix-versus-rate split
    ({"action": "decompose", "metric": "txn_count",
      "dimension": "payment_method", "window": "a", "baseline": "b"}, "reauthor"),
    ({"action": "decompose", "metric": "success_rate",
      "dimension": "not_a_dimension", "window": "a", "baseline": "b"}, "reauthor"),
    ({"action": "decompose", "metric": "success_rate",
      "dimension": "payment_method", "window": "a", "baseline": ""}, "reauthor"),
])
def test_the_author_validates_the_choice(raw, expected):
    assert validate(_coerce(raw)).action == expected


def test_a_bad_choice_is_never_reported_as_missing_data():
    a = validate(_coerce({"action": "decompose", "metric": "nope",
                          "dimension": "payment_method", "window": "a",
                          "baseline": "b"}))
    assert a.action == "reauthor" and not a.missing_concept
